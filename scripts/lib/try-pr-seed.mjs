// Creates the first admin of a pull request stack through the setup screen's sign-up, turns two-factor on with a
// TOTP code computed here, and writes the sign-in to MAANE_ADMIN_FILE (mode 600). Prints none of it.
// Run by scripts/try-pr.sh inside the toolchain container, on the stack's network. Node standard library only.
import { createHmac, randomBytes } from "node:crypto"
import { writeFile } from "node:fs/promises"

const url = process.env.MAANE_URL
const origin = process.env.MAANE_ORIGIN
const file = process.env.MAANE_ADMIN_FILE
if (!url || !origin || !file) throw new Error("MAANE_URL, MAANE_ORIGIN, and MAANE_ADMIN_FILE are required")

const username = "admin"
const password = randomBytes(18).toString("base64url")
const cookies = new Map()

async function call(path, body) {
  const headers = { origin, "content-type": "application/json", "x-forwarded-for": "198.51.100.10" }
  if (cookies.size > 0) headers.cookie = [...cookies].map(([n, v]) => `${n}=${v}`).join("; ")
  const response = await fetch(`${url}${path}`, { method: "POST", headers, body: JSON.stringify(body) })
  for (const cookie of response.headers.getSetCookie()) {
    const [pair = ""] = cookie.split(";")
    const eq = pair.indexOf("=")
    cookies.set(pair.slice(0, eq), pair.slice(eq + 1))
  }
  const text = await response.text()
  if (!response.ok) throw new Error(`${path} answered ${response.status}`)
  return text ? JSON.parse(text) : null
}

function base32Decode(input) {
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"
  let bits = ""
  for (const char of input.replace(/=+$/, "").toUpperCase()) bits += alphabet.indexOf(char).toString(2).padStart(5, "0")
  const bytes = []
  for (let i = 0; i + 8 <= bits.length; i += 8) bytes.push(Number.parseInt(bits.slice(i, i + 8), 2))
  return Buffer.from(bytes)
}

// RFC 6238, as authenticator apps compute it: SHA-1, 6 digits, 30-second steps.
function totp(secret) {
  const counter = Buffer.alloc(8)
  counter.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30_000)))
  const hmac = createHmac("sha1", base32Decode(secret)).update(counter).digest()
  const offset = hmac[hmac.length - 1] & 0xf
  return ((hmac.readUInt32BE(offset) & 0x7fffffff) % 1_000_000).toString().padStart(6, "0")
}

await call("/api/auth/sign-up/email", { name: username, email: `${username}@maane.invalid`, username, password })
const enabled = await call("/api/auth/two-factor/enable", { password })
const secret = new URL(enabled.totpURI).searchParams.get("secret") ?? ""
await call("/api/auth/two-factor/verify-totp", { code: totp(secret) })

await writeFile(
  file,
  [
    "# The first admin of the pull request stack. Generated by scripts/try-pr.sh; removed by restore.",
    `MAANE_ADMIN_USERNAME=${username}`,
    `MAANE_ADMIN_PASSWORD=${password}`,
    `MAANE_ADMIN_TOTP_SECRET=${secret}`,
    `MAANE_ADMIN_BACKUP_CODES=${enabled.backupCodes.join(",")}`,
    "",
  ].join("\n"),
  { mode: 0o600 },
)
console.log("    the first admin is ready")
